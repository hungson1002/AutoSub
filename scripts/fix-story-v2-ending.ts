import {readFile,writeFile,rename} from 'node:fs/promises';
import path from 'node:path';
import {run} from '../server/services/ffmpeg';
import type {CanvasStudioProject} from '../shared/canvasAnimationStudio';
process.env.AUTOSUB_ANIMATION_RENDER_CONCURRENCY='1';
const root=path.resolve('tmp/chiec-den-cuoi-ban-v2');
const project=JSON.parse(await readFile(path.join(root,'project.json'),'utf8')) as CanvasStudioProject;
const end=project.scenes.at(-1)!;
end.objects.find(o=>o.id==='end-title')!.y=220;
await writeFile(path.join(root,'project.json'),JSON.stringify(project,null,2),'utf8');
const {renderCanvasAnimationProject}=await import('../server/services/animationRender');
const rendered=await renderCanvasAnimationProject({...project,name:project.name+' ending correction',scenes:[end]},undefined,p=>console.log(`ENDING ${Math.floor(p*100)}%`));
const firstFrames=project.scenes.slice(0,-1).reduce((n,s)=>n+Math.round(s.durationMs*30/1000),0);
const duration=firstFrames/30;
const video=path.join(root,'chiec-den-cuoi-ban-5-phut-v2.mp4');
const corrected=path.join(root,'corrected-ending.mp4');
await run('ffmpeg',['-y','-i',video,'-i',rendered.path,'-filter_complex',`[0:v]trim=end_frame=${firstFrames},setpts=PTS-STARTPTS[v0];[0:a]atrim=end=${duration},asetpts=PTS-STARTPTS[a0];[1:v]setpts=PTS-STARTPTS[v1];[1:a]asetpts=PTS-STARTPTS[a1];[v0][a0][v1][a1]concat=n=2:v=1:a=1[v][a]`,'-map','[v]','-map','[a]','-c:v','libx264','-preset','fast','-crf','18','-r','30','-frames:v','9000','-c:a','aac','-ar','48000','-b:a','192k','-movflags','+faststart',corrected]);
await rename(video,path.join(root,'before-ending-correction.mp4'));
await rename(corrected,video);
console.log(`VIDEO=${video}`);process.exit(0);
